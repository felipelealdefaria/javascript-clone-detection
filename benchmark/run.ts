/**
 * Clone-detection benchmark.
 *
 *   npm run bench                 build the dataset (cached) and compare tools
 *   npm run bench -- --rebuild    rebuild the dataset from scratch
 *   npm run bench:embeddings      also run the embeddings experiment (downloads a model)
 *
 * Writes benchmark/results/results.{json,md}.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { buildDataset, DATA_DIR, DATASET_DIR, type Dataset } from './build.js'
import { precisionOnRealCode } from './precision.js'
import { jscpdVersion, pairKey, runAll, runSweep, type ToolRun } from './tools.js'

const RESULTS_DIR = path.join(import.meta.dirname, 'results')
const args = new Set(process.argv.slice(2))

interface Rate {
  hits: number
  total: number
}

export interface Metrics {
  tool: string
  durationMs: number
  recall: { t1: Rate; t2: Rate; t3: Rate; t4: Rate }
  recallByDomain: Record<string, { t1: Rate; t2: Rate; t3: Rate }>
  t3ByEdits: Record<string, Rate>
  precision: { truePositives: number; falsePositives: number }
}

const rate = (r: Rate) => (r.total === 0 ? 0 : r.hits / r.total)
const pct = (r: Rate) => `${(rate(r) * 100).toFixed(1)}%`
const add = (r: Rate, hit: boolean) => {
  r.total++
  if (hit) r.hits++
}
const empty = (): Rate => ({ hits: 0, total: 0 })

export function evaluate(dataset: Dataset, run: ToolRun): Metrics {
  const groupOf = new Map<string, string>()
  for (const f of dataset.families)
    for (const file of Object.values(f.files)) groupOf.set(file, f.id)
  for (const p of dataset.type4) {
    groupOf.set(p.a, p.id)
    groupOf.set(p.b, p.id)
  }

  const m: Metrics = {
    tool: run.tool,
    durationMs: Math.round(run.durationMs),
    recall: { t1: empty(), t2: empty(), t3: empty(), t4: empty() },
    recallByDomain: {},
    t3ByEdits: {},
    precision: { truePositives: 0, falsePositives: 0 },
  }
  for (const f of dataset.families) {
    m.recallByDomain[f.domain] ??= { t1: empty(), t2: empty(), t3: empty() }
    const domain = m.recallByDomain[f.domain] as { t1: Rate; t2: Rate; t3: Rate }
    m.t3ByEdits[f.t3Edits] ??= empty()
    for (const type of ['t1', 't2', 't3'] as const) {
      const hit = run.pairs.has(pairKey(f.files.original, f.files[type]))
      add(m.recall[type], hit)
      add(domain[type], hit)
      if (type === 't3') add(m.t3ByEdits[f.t3Edits] as Rate, hit)
    }
  }
  for (const p of dataset.type4) add(m.recall.t4, run.pairs.has(pairKey(p.a, p.b)))

  // Any detected pair across groups is a false positive: originals were chosen not to be clones.
  for (const key of run.pairs) {
    const [a, b] = key.split('|') as [string, string]
    if (groupOf.get(a) !== undefined && groupOf.get(a) === groupOf.get(b))
      m.precision.truePositives++
    else m.precision.falsePositives++
  }
  return m
}

function precision(m: Metrics): string {
  const { truePositives: tp, falsePositives: fp } = m.precision
  return tp + fp === 0 ? '–' : `${((tp / (tp + fp)) * 100).toFixed(1)}%`
}

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map((_, i) => (i === 0 ? '---' : '---:')).join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n')
}

function loadDataset(): Dataset {
  const file = path.join(DATA_DIR, 'dataset.json')
  if (!args.has('--rebuild') && existsSync(file) && existsSync(DATASET_DIR)) {
    return JSON.parse(readFileSync(file, 'utf8')) as Dataset
  }
  console.log('Building dataset…')
  return buildDataset()
}

async function main() {
  const dataset = loadDataset()
  const files = dataset.families.length * 4 + dataset.type4.length * 2
  console.log(
    `Dataset: ${dataset.families.length} families, ${dataset.type4.length} Type-4 pairs, ${files} files`,
  )

  const metrics = runAll(DATASET_DIR).map((run) => evaluate(dataset, run))
  const sweep = runSweep(DATASET_DIR).map(({ threshold, runs }) => ({
    threshold,
    metrics: runs.map((run) => evaluate(dataset, run)),
  }))
  const real = precisionOnRealCode()

  // The experiment downloads a model and takes minutes, so it writes its own files.
  if (args.has('--embeddings')) {
    const { embeddingsExperiment } = await import('./embeddings.js')
    const result = await embeddingsExperiment(dataset)
    writeFileSync(
      path.join(RESULTS_DIR, 'embeddings.json'),
      `${JSON.stringify(result.json, null, 2)}\n`,
    )
    writeFileSync(
      path.join(RESULTS_DIR, 'embeddings.md'),
      `${result.markdown.replace(/^## /, '# ')}\nGenerated by \`npm run bench:embeddings\`. Seed ${dataset.seed}.\n`,
    )
    console.log(result.markdown)
  }

  const env = {
    date: new Date().toISOString().slice(0, 10),
    node: process.version,
    cpu: os.cpus()[0]?.model ?? 'unknown',
    jscpd: jscpdVersion(),
  }
  writeFileSync(
    path.join(RESULTS_DIR, 'results.json'),
    `${JSON.stringify({ env, dataset: summary(dataset), metrics, sweep, realCodePrecision: real.json }, null, 2)}\n`,
  )

  const md = [
    '# Benchmark results',
    '',
    `Generated by \`npm run bench\` on ${env.date} · Node ${env.node} · ${env.cpu} · jscpd ${env.jscpd}.`,
    `Seed ${dataset.seed}. See [README.md](../README.md) for the method.`,
    '',
    `**Dataset:** ${dataset.families.length} originals (${count(dataset, 'js')} plain JS, ${count(dataset, 'react')} React) sampled from ${dataset.candidates} candidate units, after removing ${dataset.naturalClonesRemoved} that were already clones of each other. Each original has one Type-1, one Type-2 and one Type-3 mutant. Plus ${dataset.type4.length} hand-written Type-4 pairs. ${files} files in total.`,
    '',
    '## Recall by clone type',
    '',
    table(
      ['Tool', 'Type-1', 'Type-2', 'Type-3', 'Type-4', 'Precision', 'Time'],
      metrics.map((m) => [
        m.tool,
        pct(m.recall.t1),
        pct(m.recall.t2),
        pct(m.recall.t3),
        `${m.recall.t4.hits}/${m.recall.t4.total}`,
        precision(m),
        `${(m.durationMs / 1000).toFixed(2)} s`,
      ]),
    ),
    '',
    'Precision counts every detected pair across two different families as a false positive.',
    '',
    '## Type-3 recall by number of edits',
    '',
    table(
      [
        'Tool',
        ...Object.keys(metrics[0]?.t3ByEdits ?? {})
          .sort()
          .map((k) => `${k} edit${k === '1' ? '' : 's'} (n=${metrics[0]?.t3ByEdits[k]?.total})`),
      ],
      metrics.map((m) => [
        m.tool,
        ...Object.keys(m.t3ByEdits)
          .sort()
          .map((k) => pct(m.t3ByEdits[k] as Rate)),
      ]),
    ),
    '',
    '## Type-3 threshold sweep',
    '',
    'jscd scores token LCS; jscpd scores shared subtrees. Type-3 recall and precision at each cut-off:',
    '',
    table(
      [
        'Threshold',
        ...(sweep[0]?.metrics ?? []).flatMap((m) => [`${m.tool} T3`, `${m.tool} precision`]),
      ],
      sweep.map(({ threshold, metrics: ms }) => [
        threshold.toFixed(1),
        ...ms.flatMap((m) => [pct(m.recall.t3), precision(m)]),
      ]),
    ),
    '',
    '## Recall by domain',
    '',
    table(
      ['Tool', 'JS T1', 'JS T2', 'JS T3', 'React T1', 'React T2', 'React T3'],
      metrics.map((m) => [
        m.tool,
        ...(['js', 'react'] as const).flatMap((d) => {
          const r = m.recallByDomain[d]
          return r ? [pct(r.t1), pct(r.t2), pct(r.t3)] : ['–', '–', '–']
        }),
      ]),
    ),
    '',
    real.markdown,
    '## Structural vs. learned detection',
    '',
    'See [embeddings.md](embeddings.md) (`npm run bench:embeddings`).',
  ].join('\n')
  writeFileSync(path.join(RESULTS_DIR, 'results.md'), `${md.trimEnd()}\n`)
  console.log(md)
}

function count(dataset: Dataset, domain: string) {
  return dataset.families.filter((f) => f.domain === domain).length
}

function summary(dataset: Dataset) {
  return {
    seed: dataset.seed,
    candidates: dataset.candidates,
    naturalClonesRemoved: dataset.naturalClonesRemoved,
    families: dataset.families.length,
    type4Pairs: dataset.type4.length,
  }
}

await main()
